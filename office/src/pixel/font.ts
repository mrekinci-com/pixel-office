export function glyph(char: string): string[] {
  return (glyphs[char.toLocaleUpperCase(locale())] || glyphs["?"]).split("/");
}
export function textWidth(text: string, scale = 1) {
  return (
    [...text].reduce((w, c) => w + (glyph(c)[0].length + 1) * scale, 0) - scale
  );
}
export function pixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color = "#342416",
  scale = 1,
) {
  ctx.fillStyle = color;
  for (const char of text) {
    const rows = glyph(char);
    rows.forEach((row, dy) =>
      [...row].forEach((p, dx) => {
        if (p === "1")
          ctx.fillRect(
            Math.round(x + dx * scale),
            Math.round(y + dy * scale),
            scale,
            scale,
          );
      }),
    );
    x += (rows[0].length + 1) * scale;
  }
}
export function shorten(text: string, maxWidth: number) {
  let value = text;
  while (textWidth(value) > maxWidth && value.length > 1)
    value = value.slice(0, -1);
  return value === text ? value : value.slice(0, -1) + "…";
}
