import { en } from './en.js';
import { translate, type Language } from './index.js';
const keys = Object.keys(en);
const reverse = new Map(Object.entries(en).map(([key, value]) => [value as string, key]));
const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const patterns = keys.filter(key => /\{\d+\}/.test(key)).flatMap(key => [key, en[key as keyof typeof en]].map(candidate => ({
  key,
  indexes: [...candidate.matchAll(/\{(\d+)\}/g)].map(match => Number(match[1])),
  pattern: new RegExp('^' + candidate.split(/\{\d+\}/).map(escape).join('([\\s\\S]*?)') + '$'),
  specificity: candidate.replace(/\{\d+\}/g, '').length,
}))).sort((a,b) => b.specificity-a.specificity);
// Only API error messages generated by the application enter this function.
// Captured names, paths and other user values are inserted verbatim.
export function messageInfo(language: Language, message: string) {
  let key = Object.hasOwn(en, message) ? message : reverse.get(message);
  let values: string[] = [];
  if (!key) {
    for (const entry of patterns) {
      const match = entry.pattern.exec(message);
      if (!match) continue;
      key = entry.key;
      entry.indexes.forEach((index, position) => { values[index] = match[position + 1]; });
      break;
    }
  }
  if (!key) return { code: 'OFIS_ERROR', error: message };
  // Stable across languages and restarts, independent of interpolated values.
  let hash = 2166136261;
  for (const char of key) hash = Math.imul(hash ^ char.charCodeAt(0), 16777619);
  return { code: 'OFIS_' + (hash >>> 0).toString(16).padStart(8, '0').toUpperCase(), error: translate(language, key, values) };
}
