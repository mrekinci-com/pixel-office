import type { Lease } from './runtime.js';
export const TERMINAL_BUFFER_BYTES = 200_000;
export const TERMINAL_INPUT_BYTES = 16_384;
export type TerminalStatus = 'working' | 'waiting' | 'idle' | 'disconnected';
export interface TerminalSnapshot { enabled: boolean; status: TerminalStatus; generation: number; usageKnown: boolean; runner?: "claude" | "codex"; }
export type TerminalCommand = {type:'input';data:string} | {type:'resize';cols:number;rows:number};
export type TerminalToRunner = TerminalCommand | {type:'start';lease:Lease;generation:number;restart:boolean} | {type:'stop'} | {type:'inject';id:string;text:string};
export type TerminalToBrowser = {type:'output';data:string} | {type:'reset';data:string} | {type:'status';terminal:TerminalSnapshot} | {type:'error';message:string};
// Shared limits apply on both sides of the bridge; no URL, executable or agent selector.
export function terminalCommand(value:unknown):TerminalCommand | undefined {
  if(!value || typeof value!=='object')return;
  const b=value as Record<string,unknown>;
  if(b.type==='input' && typeof b.data==='string' && new TextEncoder().encode(b.data).length<=TERMINAL_INPUT_BYTES && Object.keys(b).length===2)return {type:'input',data:b.data};
  if(b.type==='resize' && typeof b.cols==='number' && typeof b.rows==='number' && Number.isInteger(b.cols) && Number.isInteger(b.rows) && b.cols>=20 && b.cols<=400 && b.rows>=5 && b.rows<=200 && Object.keys(b).length===3)return {type:'resize',cols:b.cols,rows:b.rows};
}
// Replies generated by xterm itself are not owner keystrokes or pending drafts.
export function terminalUserInput(data:string){return data.replace(/\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)/g,'').replace(/\x1bP[\s\S]*?\x1b\\/g,'').replace(/\x1b\[[0-9;?=>]*[RcntIO]/g,'');}
